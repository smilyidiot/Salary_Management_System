// Vitest setup: jest-dom matchers plus the browser APIs jsdom lacks but Mantine expects.

import '@testing-library/jest-dom/vitest'
import { afterEach, vi } from 'vitest'
import { cleanup } from '@testing-library/react'

afterEach(() => cleanup())

// Mantine components query matchMedia and ResizeObserver, which jsdom does not implement.
window.matchMedia = vi.fn().mockImplementation((query: string) => ({
  matches: false,
  media: query,
  onchange: null,
  addEventListener: vi.fn(),
  removeEventListener: vi.fn(),
  addListener: vi.fn(),
  removeListener: vi.fn(),
  dispatchEvent: vi.fn(),
}))

class ResizeObserverMock {
  observe() {}
  unobserve() {}
  disconnect() {}
}
window.ResizeObserver = ResizeObserverMock as unknown as typeof ResizeObserver

// jsdom has no layout; stub the methods Mantine/scroll code calls.
window.HTMLElement.prototype.scrollIntoView = vi.fn()
